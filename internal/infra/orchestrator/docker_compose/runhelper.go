package dockercompose

import (
	"os"
	"path/filepath"
	"strings"
)

// runRel is the manual-run helper script: derived state regenerated on every
// deploy (gitignored), mirroring winterflow's exact docker compose invocation
// so a manual run controls the same stack.
const runRel = ".winterflow/run.sh"

// managedEnvVar is reserved: the project name only ever travels as the
// --project-name flag (winterflow's invocations and run.sh), never through the
// committed .env, which belongs to the user and is often loaded into
// containers via `env_file: .env`. User variables with this name are dropped
// at save; apps saved by older agents still carry it in .env, so GetApp hides
// it until their next save rewrites the file.
const managedEnvVar = "COMPOSE_PROJECT_NAME"

// runHelperScript renders the helper for a project and its compose files
// (names are single-quoted for the shell). The env files are added in the
// order winterflow passes them, each only when it exists.
func runHelperScript(project string, files []string) []byte {
	cmd := "exec docker compose --project-name " + project
	for _, f := range files {
		cmd += " -f " + shellQuote(f)
	}
	return []byte(`#!/bin/sh
# Generated by winterflow on every deploy — do not edit.
# Runs docker compose with the same flags winterflow uses, so a manual run
# controls the same stack. Usage: .winterflow/run.sh up -d | down | logs -f
cd "$(dirname "$0")/.." || exit 1
if [ -f ` + envSecretsRel + ` ]; then set -- --env-file ` + envSecretsRel + ` "$@"; fi
if [ -f ` + storageEnvRel + ` ]; then set -- --env-file ` + storageEnvRel + ` "$@"; fi
` + cmd + ` --env-file ` + envRel + ` "$@"
`)
}

// shellQuote single-quotes s for sh.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// writeRunHelper (re)writes the app's manual-run helper.
func (r *Repository) writeRunHelper(appID string) error {
	dir := r.appDataDir(appID)
	script := runHelperScript(projectName(appID), r.composeFiles(dir, r.appSourceSpec(dir)))
	path := filepath.Join(dir, runRel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, script, 0o755); err != nil {
		return err
	}
	// WriteFile's perm only applies on create; keep regenerated files executable.
	return os.Chmod(path, 0o755)
}
