package main

import (
	"reflect"
	"sort"
	"testing"
)

func TestNonCodeLines(t *testing.T) {
	src := "package m\n" + // 1
		"\n" + // 2 blank
		"// doc\n" + // 3
		"func A() {\n" + // 4
		"\t// inside\n" + // 5
		"\treturn // trailing\n" + // 6 code
		"   \t\n" + // 7 whitespace only
		"\t/* one line */\n" + // 8
		"\t/* start\n" + // 9
		"\t   middle\n" + // 10
		"\t   end */\n" + // 11
		"\tx := 1 /* c */\n" + // 12 code
		"\t/* c */ y := 2\n" + // 13 code
		"\t/* a\n" + // 14
		"\t   b */ z := 3\n" + // 15 comment ends, code follows
		"}\n" // 16
	got := nonCodeLines([]byte(src))
	var lines []int
	for n := range got {
		lines = append(lines, n)
	}
	sort.Ints(lines)
	want := []int{2, 3, 5, 7, 8, 9, 10, 11, 14}
	if !reflect.DeepEqual(lines, want) {
		t.Fatalf("got %v, want %v", lines, want)
	}
}

func TestIsGenerated(t *testing.T) {
	cases := map[string]bool{
		"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n":        true,
		"// Copyright\n\n// Code generated by sqlc. DO NOT EDIT.\n\npackage p\n": true,
		"package p\n\n// Code generated by hand. DO NOT EDIT.\n":                 false, // after the package clause
		"// Code generated but editable\npackage p\n":                            false,
		"// code generated by x. DO NOT EDIT.\npackage p\n":                      false, // marker is case-sensitive
		"//Code generated by x. DO NOT EDIT.\npackage p\n":                       false,
		"package p\n": false,
		"":            false,
	}
	for src, want := range cases {
		if got := isGenerated([]byte(src)); got != want {
			t.Errorf("isGenerated(%q) = %v, want %v", src, got, want)
		}
	}
}
