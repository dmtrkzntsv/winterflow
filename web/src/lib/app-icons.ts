export const APP_ICON_NAMES = Object.keys(APP_ICONS);

// pascalize turns "bar-chart" / "bar_chart" into "BarChart" so legacy v2
// kebab-case values still resolve.
function pascalize(name: string): string {
  return name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

// getAppIcon resolves a stored icon name to its component. It accepts the
// canonical PascalCase name (v1) and tolerates kebab/snake-case.
export function getAppIcon(name?: string): LucideIcon | undefined {
  if (!name) return undefined;
  return APP_ICONS[name] ?? APP_ICONS[pascalize(name)];
}
